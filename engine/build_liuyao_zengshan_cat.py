def main():
    src = json.load(io.open(SRC, encoding='utf-8'))
    vocab = set(json.load(io.open(VOCAB, encoding='utf-8')))

    out_volumes = []
    flat = 0
    total_rules = 0
    for v in src['volumes']:
        chs = []
        for c in v['chapters']:
            flat += 1
            rules = RULES.get(flat, [])
            # 词汇表自检：每条 cond 至少含一个词汇短语
            for r in rules:
                if not any(w in r['cond'] for w in vocab):
                    raise SystemExit('[词汇表未覆盖] 章%d cond=%r' % (flat, r['cond']))
            huobu = HUOBU_OVERRIDE.get(flat, DEFAULT_HUOBU)
            assert huobu, '章%d 活步骤为空' % flat
            total_rules += len(rules)
            chs.append({'name': c['name'], 'rules': rules, 'huobu': huobu})
        out_volumes.append({'vol': v['vol'], 'chapters': chs})

    doc = {
        'format': 'zengshan-cat/1',
        'note': '增删卜易4卷120章机判化层。rules cond 必须被 ly_cond_vocab2.json 词汇表覆盖；未提炼者归 huobu（活步骤）。duan 压缩自原文，不杜撰。野鹤断验案例不硬凑机判。',
        'volumes': out_volumes,
    }
    io.open(DST, 'w', encoding='utf-8').write(
        json.dumps(doc, ensure_ascii=False, indent=1))
    nch = sum(len(v['chapters']) for v in out_volumes)
    print('OK 写出', DST)
    print('卷数=%d 章数=%d 规则数=%d 词汇表=%d' % (len(out_volumes), nch, total_rules, len(vocab)))


if __name__ == '__main__':
    main()
