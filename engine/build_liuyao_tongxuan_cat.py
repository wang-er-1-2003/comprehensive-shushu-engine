def main():
    vocab = set(json.load(io.open(VOCAB, encoding='utf-8')))
    src = json.load(io.open(SRC, encoding='utf-8'))
    src_names = [re.sub(r'[：:].*$', '', c['name']).strip() for c in src['fenlei']]
    assert len(src_names) == len(CATS) == 42, (len(src_names), len(CATS))
    out_cats = []
    n_rule = 0
    n_huobu = 0
    for i, (nm, rules, huobu) in enumerate(CATS):
        assert nm == src_names[i], '类名不对位 %d: %s vs %s' % (i, nm, src_names[i])
        rs = []
        for cond, duan, sub in rules:
            assert any(w in cond for w in vocab), 'cond 未被词汇表覆盖: %s (%s)' % (cond, nm)
            rs.append({"cond": cond, "duan": duan, "src": '%s·%s·%s' % (BOOK, nm, sub)})
        hb = list(huobu)
        for h in hb:
            assert isinstance(h.get('title'), str) and h['title'] not in ('title', 'steps', ''), c.name + ' 活步骤标题占位: ' + repr(h.get('title'))
            assert isinstance(h.get('steps'), list) and len(h['steps']) >= 1, c.name + ' 活步骤 steps 非数组'
            for st in h['steps']:
                assert isinstance(st, str) and st not in ('steps', ''), c.name + ' 活步骤步占位: ' + repr(st)
        assert len(hb) >= 1, nm
        n_rule += len(rs)
        n_huobu += len(hb)
        out_cats.append({"name": nm, "rules": rs, "huobu": hb})
    doc = {
        "format": "liuyao_tongxuan_cat",
        "note": "断易通玄赋分类占 42 类：cond 机判规则（由 lyFenMatch/lyCatCondEval 求值，cond 中文关键词均在既有词汇表内）+ 活步骤（红色加粗，需人按步对照卦象）。duan 取原文韵文/断语句，可压缩不杜撰；提炼不出的如实归活步骤。",
        "cats": out_cats,
    }
    io.open(OUT, 'w', encoding='utf-8').write(json.dumps(doc, ensure_ascii=False, indent=1))
    print('写出', OUT)
    print('类数', len(out_cats), '规则总数', n_rule, '活步骤组数', n_huobu)


if __name__ == '__main__':
    main()
