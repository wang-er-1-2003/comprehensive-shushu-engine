def main():
    src = json.load(io.open(SRC, encoding='utf-8'))
    fl = src['fenlei']
    assert len(fl) == 1046, 'fenlei 条数异常: %d' % len(fl)
    vocab = set(json.load(io.open(VOCAB, encoding='utf-8')))

    rules = []
    for tiao, cond, duan in RULES_RAW:
        if not (1 <= tiao <= len(fl)):
            raise SystemExit('条号越界: %d' % tiao)
        if not any(w in cond for w in vocab):
            raise SystemExit('[词汇表未覆盖] 第%d条 cond=%r' % (tiao, cond))
        rules.append(R(tiao, cond, duan))

    doc = {
        'format': 'qj-jiedu-cat/1',
        'note': '黄金策解读·分类占1046条机判化层。rules cond 必须被 ly_cond_vocab2.json 词汇表覆盖；提不出者归 huobu（活步骤），宁缺毋滥。duan 压缩自解读原文，不杜撰。qianjin 68条已由 lyQianjinHits 机判，本层不碰。',
        'rules': rules,
        'huobu': HUOBU,
    }
    io.open(DST, 'w', encoding='utf-8').write(json.dumps(doc, ensure_ascii=False, indent=1))
    print('OK 写出', DST)
    print('源条数=%d 提炼规则=%d 活步骤组=%d 词汇表=%d' % (len(fl), len(rules), len(HUOBU), len(vocab)))


if __name__ == '__main__':
    main()
