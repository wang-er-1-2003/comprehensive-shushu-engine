# ── 3. 何知章（滴天髓 1149-1268 行，取"何知"四句 + 原注）──
def parse_hezhi():
    lines = read("滴天髓阐微.txt")
    out = {}
    keys = ["富", "贵", "贫", "贱", "吉", "凶", "寿", "夭"]
    # 每项起始行：何知其人X？
    starts = {}
    for i, line in enumerate(lines):
        m = re.match(r"何知其人([富贵贫贱吉凶寿夭])[？?]", line.strip())
        if m:
            starts[m.group(1)] = i
    order = ["富", "贵", "贫", "贱", "吉", "凶", "寿", "夭"]
    for idx, k in enumerate(order):
        i = starts.get(k)
        if i is None:
            continue
        four = lines[i].strip()
        note = ""
        # 原注：下一行是【原注】... 直到【任氏曰】或命例
        j = i + 1
        while j < len(lines) and not lines[j].strip().startswith("【任氏曰】"):
            s = lines[j].strip()
            if s.startswith("【原注】"):
                note = s[4:].strip()
            elif s and not re.match(r"^[甲乙丙丁戊己庚辛壬癸]{2}[ ][甲乙丙丁戊己庚辛壬癸]{2}[ ][甲乙丙丁戊己庚辛壬癸]{2}[ ][甲乙丙丁戊己庚辛壬癸]{2}$", s) and not re.match(r"^[甲乙丙丁戊己庚辛壬癸]{4}$", s) and not s.startswith("何知"):
                note = note + ("" if not note else " ") + s
            j += 1
        out[k] = {"four": four, "yuanzhu": note[:200]}
    return out

