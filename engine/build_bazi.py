# ── 5. 实践应验断语八百条 12 类 ──
def parse_duanyu12():
    lines = read("实践应验断语八百条.txt")
    cats = []
    cur = None
    sub = None
    for line in lines:
        s = line.strip()
        m = re.match(r"^##\s*([0-9]+)\.(.+)$", s)
        if m:
            cur = {"cat": m.group(2).strip(), "items": []}
            cats.append(cur)
            sub = None
            continue
        sm = re.match(r"^###\s*(.+)$", s)
        if sm:
            sub = sm.group(1).strip()
            continue
        if cur is not None:
            mm = re.match(r"^[0-9]{3}\s+(.+)$", s)
            if mm:
                cur["items"].append({"text": mm.group(1).strip(), "sub": sub})
    return cats

# ── 5b. 三命通会 论十二月支得日干吉凶（3093-3290，12月×5日干组）──
def parse_shier_yueji():
    lines = read("三命通会.txt")
    seg = lines[3092:3290]  # 0-based 3093..3289
    out = {}
    cur_m = None
    cur_key = None
    buf = []
    month_re = re.compile(r"^([子丑寅卯辰巳午未申酉戌亥])月$")
    day_re = re.compile(r"^((?:[甲丙戊庚壬][乙丁己辛癸]?|戌己)[日月])")
    GRP = {"甲": "甲乙", "丙": "丙丁", "戊": "戊己", "庚": "庚辛", "壬": "壬癸", "戌": "戊己"}
    def flush():
        nonlocal cur_m, cur_key, buf
        if cur_m is not None and cur_key is not None:
            out[cur_m][cur_key] = f2s("\n".join(buf)).strip()
        buf = []
    for line in seg:
        s = line.strip()
        mm = month_re.match(s)
        if mm:
            flush()
            cur_m = mm.group(1)
            if cur_m not in out:
                out[cur_m] = {}
            cur_key = None
            continue
        dm = day_re.match(s)
        if dm and cur_m is not None:
            flush()
            cur_key = GRP[dm.group(1)[0]]
            continue
        if cur_m is not None and cur_key is not None and s:
            buf.append(s)
    flush()
    return out

# ── 5c. 三命通会 六甲至六癸日十二时断（5663-8672，十组日干×十二时=120段）──
def parse_shishizhen():
    lines = read("三命通会.txt")
    seg = lines[5662:8673]  # 0-based 5663..8672（8673 为章节收尾注，不含）
    out = {}
    anchor = re.compile(r"^六([甲乙丙丁戊己庚辛壬癸])日([甲乙丙丁戊己庚辛壬癸])([子丑寅卯辰巳午未申酉戌亥])時斷")
    cur = None
    buf = []
    def flush():
        nonlocal cur, buf
        if cur is not None:
            out[cur["day"]][cur["hour"]] = {"title": cur["title"], "text": f2s("\n".join(buf)).strip()}
        buf = []
    for line in seg:
        s = line.strip()
        m = anchor.match(s)
        if m:
            flush()
            d = m.group(1)
            h = m.group(2) + m.group(3)
            cur = {"day": d, "hour": h, "title": f2s(s)}
            if d not in out:
                out[d] = {}
        elif cur is not None and s:
            buf.append(s)
    flush()
    return out

