# ── 6. 子平真诠八格取运原文（评注版行号）──
def parse_ge_xiyi():
    lines = read("子平真诠评注.txt")
    anchors = [
        ("正官", 979, 1033), ("财", 1033, 1112), ("印", 1112, 1198),
        ("食神", 1198, 1277), ("偏官", 1277, 1341), ("伤官", 1341, 1401),
        ("阳刃", 1401, 1430), ("建禄月劫", 1430, 1500),
    ]
    out = {}
    for name, a, b in anchors:
        seg = []
        for i in range(a - 1, min(b - 1, len(lines))):
            s = lines[i].strip()
            if s.startswith("原文："):
                seg.append(s[3:].strip())
                break
        if seg:
            out[name] = seg[0]
    return out

